const reactGlobals: BunPlugin = {
  name: "react-globals",
  setup(build) {
    build.onResolve({ filter: /^react(-dom)?(\/.*)?$/ }, (args) => ({
      path: args.path,
      namespace: "react-global",
    }));
    build.onLoad({ filter: /.*/, namespace: "react-global" }, (args) => {
      if (args.path.startsWith("react/jsx")) {
        return {
          loader: "js",
          contents: `const R = window.React;
export const Fragment = R.Fragment;
export function jsx(type, props, key) { return R.createElement(type, key === undefined ? props : Object.assign({}, props, { key })); }
// Static children arrive as an array; spread them so React doesn't treat them as a keyed list.
export function jsxs(type, props, key) {
  const { children, ...rest } = props;
  if (key !== undefined) rest.key = key;
  return R.createElement.apply(null, [type, rest].concat(children));
}
export const jsxDEV = jsx;`,
        };
      }
      if (args.path.startsWith("react-dom"))
        return { loader: "js", contents: "module.exports = window.ReactDOM;" };
      return { loader: "js", contents: "module.exports = window.React;" };
    });
  },
};

/** Consumers inline bundle.js/bundle.css into <script>/<style>: these sequences would end them. */
function inlineSafe(code: string, kind: "js" | "css"): string {
  if (kind === "js")
    return code.replaceAll("</script", "<\\/script").replaceAll("<!--", "\\x3C!--");
  if (/<\/style/i.test(code)) throw new Error("bundle.css contains </style");
  return code;
}

async function buildJs(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(root, "scripts/artifact-entry.tsx")],
    format: "iife",
    target: "browser",
    minify: true,
    plugins: [reactGlobals],
    define: { "process.env.NODE_ENV": '"production"' },
    tsconfig: join(root, "tsconfig.json"),
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("artifact bundle failed");
  }
  const kit = await result.outputs[0]?.text();
  if (!kit) throw new Error("empty artifact bundle");

  const base = await Bun.file(join(art, "base/bundle.js")).text();
  const [first = "", ...rest] = base.split("\n");
  const m = /^\/\* @ds-bundle: (.*) \*\/$/.exec(first);
  if (!m?.[1]) throw new Error("base bundle.js has no @ds-bundle header");
  const header = JSON.parse(m[1]) as { components: { name: string }[] };
  for (const name of KIT_COMPONENTS) {
    if (!header.components.some((c) => c.name === name)) header.components.push({ name });
  }
  return inlineSafe(
    [
      `/* @ds-bundle: ${JSON.stringify(header)} */`,
      ...rest,
      "/* Ledger/01 kit components (generated by packages/ui/scripts/build-artifact.ts) */",
      kit,
    ].join("\n"),
    "js",
  );
}

async function buildCss(): Promise<string> {
  const from = join(root, "src/styles/artifact.css");
  const result = await postcss([tailwind({ base: root })]).process(await Bun.file(from).text(), {
    from,
  });
  const base = await Bun.file(join(art, "base/bundle.css")).text();
  return inlineSafe(
    `${base}\n/* Ledger/01 kit utilities (generated by packages/ui/scripts/build-artifact.ts) */\n${result.css}`,
    "css",
  );
}

